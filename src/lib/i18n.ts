export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] === undefined ? `{${key}}` : String(vars[key]),
  );
}

export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = dictionaries[locale] ?? dictionaries.en;
  return interpolate(table[key] ?? dictionaries.en[key] ?? key, vars);
}

export function detectLocale(input?: {
  cookie?: string | null;
  acceptLanguage?: string | null;
  navigatorLanguage?: string | null;
}): Locale {
  const cookie = input?.cookie?.toLowerCase();
  if (cookie === "tr" || cookie === "en") return cookie;
  const header = (input?.navigatorLanguage || input?.acceptLanguage || "").toLowerCase();
  if (header.startsWith("tr")) return "tr";
  return "en";
}

